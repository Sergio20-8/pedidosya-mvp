-- PedidosYa MVP v2 - esquema base
-- No ejecutar directamente con la clave publishable desde el frontend.

create extension if not exists pgcrypto;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create table public.perfiles (
  id uuid primary key references auth.users(id) on delete cascade,
  nombre varchar(120) not null,
  telefono varchar(30),
  rol varchar(20) not null default 'CLIENTE' check (rol in ('CLIENTE','REPARTIDOR','ADMIN')),
  activo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.zonas (
  id uuid primary key default gen_random_uuid(),
  nombre varchar(100) not null unique,
  descripcion text,
  activa boolean not null default true,
  bloqueada boolean not null default false,
  bloqueada_desde timestamptz,
  updated_at timestamptz not null default now()
);

create table public.categorias (
  id uuid primary key default gen_random_uuid(),
  nombre varchar(100) not null unique,
  imagen_url text,
  orden integer not null default 0,
  activa boolean not null default true
);

create table public.restaurantes (
  id uuid primary key default gen_random_uuid(),
  zona_id uuid not null references public.zonas(id) on delete restrict,
  nombre varchar(150) not null,
  descripcion text,
  imagen_url text,
  banner_url text,
  tiempo_preparacion_min integer not null default 20 check (tiempo_preparacion_min > 0),
  pos_x numeric(10,3),
  pos_y numeric(10,3),
  activo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.direcciones (
  id uuid primary key default gen_random_uuid(),
  cliente_id uuid not null references public.perfiles(id) on delete restrict,
  alias varchar(60),
  detalle text not null,
  referencia text,
  zona_id uuid not null references public.zonas(id) on delete restrict,
  predeterminada boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.productos (
  id uuid primary key default gen_random_uuid(),
  restaurante_id uuid not null references public.restaurantes(id) on delete restrict,
  categoria_id uuid not null references public.categorias(id) on delete restrict,
  nombre varchar(150) not null,
  descripcion text,
  precio numeric(12,2) not null check (precio >= 0),
  imagen_url text,
  disponible boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.grupos_opciones (
  id uuid primary key default gen_random_uuid(),
  producto_id uuid not null references public.productos(id) on delete restrict,
  nombre varchar(100) not null,
  obligatorio boolean not null default false,
  min_selecciones integer not null default 0 check (min_selecciones >= 0),
  max_selecciones integer not null check (max_selecciones > 0),
  orden integer not null default 0,
  check (min_selecciones <= max_selecciones),
  check ((not obligatorio) or min_selecciones > 0)
);

create table public.opciones_producto (
  id uuid primary key default gen_random_uuid(),
  grupo_id uuid not null references public.grupos_opciones(id) on delete restrict,
  nombre varchar(100) not null,
  precio_extra numeric(12,2) not null default 0 check (precio_extra >= 0),
  disponible boolean not null default true,
  orden integer not null default 0
);

create table public.promociones (
  id uuid primary key default gen_random_uuid(),
  restaurante_id uuid references public.restaurantes(id) on delete restrict,
  titulo varchar(150) not null,
  descripcion text,
  imagen_url text,
  tipo varchar(20) not null default 'BANNER' check (tipo in ('BANNER','DESCUENTO')),
  descuento_porcentaje numeric(5,2) check (descuento_porcentaje >= 0 and descuento_porcentaje <= 100),
  inicio timestamptz,
  fin timestamptz,
  activa boolean not null default true,
  check (fin is null or inicio is null or fin > inicio),
  check (tipo = 'BANNER' or descuento_porcentaje is not null)
);

create table public.repartidores (
  id uuid primary key default gen_random_uuid(),
  perfil_id uuid not null unique references public.perfiles(id) on delete restrict,
  zona_id uuid references public.zonas(id) on delete restrict,
  disponible boolean not null default false,
  pos_x numeric(10,3),
  pos_y numeric(10,3),
  activo boolean not null default true,
  es_demo boolean not null default false,
  updated_at timestamptz not null default now()
);

create table public.pedidos (
  id uuid primary key default gen_random_uuid(),
  numero bigint generated by default as identity unique,
  solicitud_id uuid not null unique,
  cliente_id uuid not null references public.perfiles(id) on delete restrict,
  restaurante_id uuid not null references public.restaurantes(id) on delete restrict,
  zona_id uuid not null references public.zonas(id) on delete restrict,
  direccion_id uuid references public.direcciones(id) on delete restrict,
  direccion_snapshot text not null,
  estado varchar(20) not null default 'PENDIENTE' check (estado in ('PENDIENTE','ASIGNADO','RECOGIDO','EN_CAMINO','ENTREGADO','CANCELADO')),
  subtotal numeric(12,2) not null check (subtotal >= 0),
  descuento numeric(12,2) not null default 0 check (descuento >= 0),
  costo_envio numeric(12,2) not null default 0 check (costo_envio >= 0),
  total numeric(12,2) not null check (total >= 0),
  eta_minutos integer check (eta_minutos >= 0),
  confirmado_en timestamptz,
  finalizado_en timestamptz,
  es_demo boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (descuento <= subtotal),
  check (total = subtotal - descuento + costo_envio)
);

create table public.pedido_detalles (
  id uuid primary key default gen_random_uuid(),
  pedido_id uuid not null references public.pedidos(id) on delete restrict,
  producto_id uuid not null references public.productos(id) on delete restrict,
  nombre_producto_snapshot varchar(150) not null,
  cantidad integer not null check (cantidad > 0),
  precio_base_unitario numeric(12,2) not null check (precio_base_unitario >= 0),
  precio_opciones_unitario numeric(12,2) not null default 0 check (precio_opciones_unitario >= 0),
  subtotal_linea numeric(12,2) not null check (subtotal_linea >= 0),
  observaciones text,
  opciones_snapshot jsonb not null default '[]'::jsonb,
  check (subtotal_linea = cantidad * (precio_base_unitario + precio_opciones_unitario))
);

create table public.asignaciones (
  id uuid primary key default gen_random_uuid(),
  pedido_id uuid not null references public.pedidos(id) on delete restrict,
  repartidor_id uuid not null references public.repartidores(id) on delete restrict,
  distancia_simulada numeric(12,3) not null check (distancia_simulada >= 0),
  carga_antes integer not null check (carga_antes >= 0),
  criterio varchar(60) not null default 'MENOR_CARGA_DISTANCIA',
  asignada_en timestamptz not null default now(),
  terminada_en timestamptz,
  motivo_fin varchar(30)
);

create table public.eventos_pedido (
  id uuid primary key default gen_random_uuid(),
  pedido_id uuid not null references public.pedidos(id) on delete restrict,
  tipo_evento varchar(40) not null,
  estado_anterior varchar(20),
  estado_nuevo varchar(20),
  actor_id uuid references public.perfiles(id) on delete restrict,
  origen varchar(20) not null check (origen in ('SISTEMA','CLIENTE','REPARTIDOR','ADMIN')),
  detalle text,
  created_at timestamptz not null default now()
);

create table public.cancelaciones (
  id uuid primary key default gen_random_uuid(),
  pedido_id uuid not null unique references public.pedidos(id) on delete restrict,
  motivo_codigo varchar(50) not null,
  descripcion text,
  origen varchar(20) not null check (origen in ('SISTEMA','CLIENTE','REPARTIDOR','ADMIN')),
  actor_id uuid references public.perfiles(id) on delete restrict,
  created_at timestamptz not null default now()
);

create table public.reembolsos (
  id uuid primary key default gen_random_uuid(),
  pedido_id uuid not null unique references public.pedidos(id) on delete restrict,
  cancelacion_id uuid not null unique references public.cancelaciones(id) on delete restrict,
  motivo_codigo varchar(50) not null,
  monto numeric(12,2) not null check (monto >= 0),
  automatico boolean not null,
  estado varchar(30) not null check (estado in ('SIMULADO_PENDIENTE','SIMULADO_COMPLETADO','REVISION_MANUAL','REVISION_APROBADA','REVISION_RECHAZADA')),
  revisado_por uuid references public.perfiles(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.notificaciones (
  id uuid primary key default gen_random_uuid(),
  destinatario_id uuid not null references public.perfiles(id) on delete restrict,
  pedido_id uuid references public.pedidos(id) on delete restrict,
  tipo varchar(40) not null,
  titulo varchar(140) not null,
  mensaje text not null,
  leida_en timestamptz,
  created_at timestamptz not null default now()
);

create table public.escenarios_demo (
  id uuid primary key default gen_random_uuid(),
  codigo varchar(40) not null unique,
  nombre varchar(100) not null,
  descripcion text,
  configuracion jsonb not null default '{}'::jsonb,
  activo boolean not null default true
);

create table public.ejecuciones_demo (
  id uuid primary key default gen_random_uuid(),
  escenario_id uuid not null references public.escenarios_demo(id) on delete restrict,
  ejecutado_por uuid not null references public.perfiles(id) on delete restrict,
  resultado jsonb,
  created_at timestamptz not null default now()
);

