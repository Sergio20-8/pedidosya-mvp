create or replace function public.crear_perfil_cliente()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.perfiles (id, nombre, telefono, rol)
  values (
    new.id,
    left(coalesce(new.raw_user_meta_data ->> 'nombre', split_part(coalesce(new.email, 'Cliente'), '@', 1)), 120),
    left(new.raw_user_meta_data ->> 'telefono', 30),
    'CLIENTE'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.crear_perfil_cliente();

revoke all on function public.crear_perfil_cliente() from public;

